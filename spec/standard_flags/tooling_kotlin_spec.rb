require "spec_helper"
require "open3"
require "shellwords"
require "tmpdir"

RSpec.describe StandardFlags::Tooling::Kotlin do
  let(:snapshot) { File.expand_path("../fixtures/kotlin/StandardFlags.kt", __dir__) }

  # The kotlinc command: KOTLINC (a command line) when set, else a kotlinc on
  # the PATH that runs, else nil (the compile example is skipped).
  def kotlinc
    return Shellwords.split(ENV["KOTLINC"]) unless ENV["KOTLINC"].to_s.strip.empty?

    _, status = Open3.capture2e("kotlinc", "-version")
    [ "kotlinc" ] if status.success?
  rescue SystemCallError
    nil
  end

  def define_sample
    StandardFlags.config.audiences = { mobile: {}, web: {}, pre_auth: { public: true }, kiosk: {} }
    define_flags do
      flag :new_checkout, owner: "payments", remove_by: "2027-03-01", final: true,
                          expose: { web: :newCheckout, mobile: :newCheckout }, min_client: { android: "0.4.0" }
      kill_switch :ai_assistant, owner: "assistant", expose: { web: :assistant, mobile: %i[chat chatEnabled] }
      mode :strict_gates, owner: "platform", preset: :sensor, expose: { web: :strict_gates }
      mode :review_flow, owner: "platform", values: %i[off two-step 2fa], permanent: true, expose: { pre_auth: :reviewFlow }
      experiment :home_hero, owner: "growth", variants: [ "control", "save $5", "contrôle", "a\"b\\c", "control-a", "control_a" ],
                             expose: { mobile: :homeHero }
      experiment :server_only, owner: "growth", variants: %w[a b]
      tombstone :chat_v1, removed: "2026-12-01", serve: { mobile: { chat_v1: false, chatMode: "basic" } }, until: "2027-03-01"
      tombstone :manual_entry, removed: "2026-12-01"
    end
  end

  it "matches the snapshot (UPDATE_SNAPSHOTS=1 rewrites it)" do
    define_sample
    source = described_class.new(package: "com.example.flags").render
    if ENV["UPDATE_SNAPSHOTS"] == "1"
      FileUtils.mkdir_p(File.dirname(snapshot))
      File.write(snapshot, source.sub(/sha256 \h{64}/, "sha256 <digest>").sub(/SHA256: String = "\h{64}"/, 'SHA256: String = "<digest>"'))
    end

    digest = StandardFlags::Tooling::Manifest.new.digest
    expect(source).to eq(File.read(snapshot).gsub("<digest>", digest))
  end

  it "writes only ASCII, and passes the syntax check" do
    define_sample
    source = described_class.new(package: "com.example.flags").render

    expect(source).to be_ascii_only
    expect(KotlinSyntax.check!(source)).to be(true)
    expect(KotlinSyntax.check!(described_class.new(package: nil).render)).to be(true)
    expect(KotlinSyntax.check!(described_class.new(registry: StandardFlags::Registry.empty).render)).to be(true)
  end

  it "names the manifest version and digest in the header and StandardFlagsManifest" do
    define_sample
    source = described_class.new.render
    digest = StandardFlags::Tooling::Manifest.new.digest

    expect(source.lines.first(2).join).to eq(<<~KT)
      // Generated by `bin/rails standard_flags:kotlin`. Do not edit by hand.
      // Manifest version 2, sha256 #{digest}.
    KT
    expect(source).to include("const val VERSION: Int = 2\n", "const val SHA256: String = \"#{digest}\"\n")
    expect(source).not_to include("package ")
  end

  it "uses config.kotlin_package by default" do
    StandardFlags.config.kotlin_package = "org.example.app.flags"
    expect(described_class.new(registry: StandardFlags::Registry.empty).render).to include("\npackage org.example.app.flags\n")
  end

  it "keeps enum entries in wire-name order whatever the declaration order" do
    define_flags do
      kill_switch :zeta, owner: "x", expose: { mobile: :alpha }
      kill_switch :alpha, owner: "x", expose: { mobile: :zulu }
      kill_switch :mid, owner: "x", expose: { mobile: %i[mike bravo] }
    end
    entries = described_class.new.render.scan(/^    ([A-Z_]+)\("/).flatten
    expect(entries).to eq(%w[ALPHA BRAVO MIKE ZULU])
  end

  it "renders an empty registry" do
    expect(described_class.new(registry: StandardFlags::Registry.empty).render).to end_with(<<~KT)
      /** A wire's JSON type. */
      enum class FeatureType { BOOLEAN, STRING }
    KT
  end

  [ "", "com..flags", "com.example.object", "1com.example", "com.exa-mple", "com.example." ].each do |name|
    it "refuses the package #{name.inspect}" do
      expect { described_class.new(registry: StandardFlags::Registry.empty, package: name) }
        .to raise_error(StandardFlags::ConfigurationError, /is not a Kotlin package name/)
    end
  end

  it "refuses two wires of one audience that would be the same entry" do
    define_flags do
      kill_switch :a, owner: "x", expose: { mobile: :chatEnabled }
      kill_switch :b, owner: "x", expose: { mobile: :chat_enabled }
    end
    expect { described_class.new.render }
      .to raise_error(described_class::NameClash, /wires "chatEnabled" and "chat_enabled" of audience mobile are both CHAT_ENABLED/)
  end

  it "refuses generated type names that clash or aren't identifiers" do
    define_flags do
      mode :a_b1, owner: "x", preset: :sensor, expose: { web: :one }
      mode :a_b_1, owner: "x", preset: :sensor, expose: { web: :two }
    end
    expect { described_class.new.render }.to raise_error(described_class::NameClash, /both generate Kotlin type AB1Value/)

    StandardFlags.config.audiences = { "my-app": {} }
    define_flags { kill_switch :a, owner: "x", expose: { "my-app": :a } }
    expect { described_class.new.render }.to raise_error(described_class::NameClash, /"My-appFeature", which is not a Kotlin identifier/)
  end

  describe ".string and .constant" do
    it "escapes quotes, backslashes, dollars and anything outside printable ASCII" do
      expect(described_class.string(%(a"b\\c$dé\n\u{1F600}))).to eq('"a\\"b\\\\c\\$d\\u00E9\\u000A\\uD83D\\uDE00"')
    end

    it "makes SCREAMING_SNAKE_CASE names" do
      expect(%w[homeHero chat_v1 HTTPServer two-step 2fa - save\ $5].map { |text| described_class.constant(text) })
        .to eq(%w[HOME_HERO CHAT_V1 HTTP_SERVER TWO_STEP V_2FA V SAVE_5])
    end
  end

  describe "KotlinSyntax" do
    {
      "an unbalanced brace" => "enum class A { B,\n",
      "a bad escape" => %(object A { const val B: String = "\\q" }),
      "an unescaped dollar" => %(object A { const val B: String = "$x" }),
      "a keyword as a name" => "enum class object { A }",
      "an unknown declaration" => "fun main() {}",
      "a stray character" => "enum class A { B# }"
    }.each do |label, source|
      it "rejects #{label}" do
        expect { KotlinSyntax.check!(source) }.to raise_error(KotlinSyntax::Error)
      end
    end
  end

  it "compiles with kotlinc (set KOTLINC to a command, or put kotlinc on the PATH)" do
    compiler = kotlinc
    skip "kotlinc is not available" unless compiler

    define_sample
    Dir.mktmpdir do |dir|
      File.write(File.join(dir, "StandardFlags.kt"), described_class.new(package: "com.example.flags").render)
      File.write(File.join(dir, "Use.kt"), <<~KT)
        package com.example.flags

        fun main() {
            check(MobileFeature.fromWire("homeHero") == MobileFeature.HOME_HERO)
            check(MobileFeature.HOME_HERO.type == FeatureType.STRING)
            check(HomeHeroValue.fromValue("contr\\u00f4le") == HomeHeroValue.CONTR_LE)
            check(HomeHeroValue.fromValue("save \\$5") == HomeHeroValue.SAVE_5)
            check(ReviewFlowValue.fromValue("2fa") == ReviewFlowValue.V_2FA)
            check(WebFeature.fromWire("chat") == null)
            check(StandardFlagsManifest.SHA256.length == 64)
            println("ok")
        }
      KT
      jar = File.join(dir, "out.jar")
      output, status = Open3.capture2e(*compiler, "-Werror", "-include-runtime", "-d", jar,
                                       File.join(dir, "StandardFlags.kt"), File.join(dir, "Use.kt"))
      expect(status).to be_success, output
      run, = Open3.capture2e("java", "-jar", jar)
      expect(run).to eq("ok\n")
    end
  end
end
